CREATE TABLE IF NOT EXISTS `tz_calendar_events` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `team_id` BIGINT UNSIGNED NOT NULL,
  `company_id` BIGINT UNSIGNED DEFAULT NULL,
  `user_id` BIGINT UNSIGNED DEFAULT NULL,
  `created_by_team_id` BIGINT UNSIGNED DEFAULT NULL,
  `title` VARCHAR(255) NOT NULL,
  `description` TEXT NULL,
  `event_type` VARCHAR(80) DEFAULT 'event',
  `status` VARCHAR(50) DEFAULT 'active',
  `source_type` VARCHAR(80) DEFAULT 'manual',
  `source_id` BIGINT UNSIGNED DEFAULT NULL,
  `owner_type` VARCHAR(120) DEFAULT NULL,
  `owner_id` BIGINT UNSIGNED DEFAULT NULL,
  `starts_at` DATETIME NOT NULL,
  `ends_at` DATETIME NULL,
  `all_day` TINYINT(1) DEFAULT 0,
  `timezone` VARCHAR(64) DEFAULT 'Australia/Melbourne',
  `color` VARCHAR(20) DEFAULT NULL,
  `location` VARCHAR(255) DEFAULT NULL,
  `external_uid` VARCHAR(191) DEFAULT NULL,
  `sync_state` VARCHAR(50) DEFAULT NULL,
  `meta_json` JSON NULL,
  `created_at` TIMESTAMP NULL DEFAULT NULL,
  `updated_at` TIMESTAMP NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_tz_calendar_events_team_start` (`team_id`,`starts_at`),
  KEY `idx_tz_calendar_events_source` (`source_type`,`source_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `tz_calendar_recurrence_rules` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `team_id` BIGINT UNSIGNED NOT NULL,
  `company_id` BIGINT UNSIGNED DEFAULT NULL,
  `user_id` BIGINT UNSIGNED DEFAULT NULL,
  `created_by_team_id` BIGINT UNSIGNED DEFAULT NULL,
  `calendar_event_id` BIGINT UNSIGNED NOT NULL,
  `frequency` VARCHAR(20) NOT NULL,
  `interval_value` INT UNSIGNED NOT NULL DEFAULT 1,
  `days_of_week` JSON NULL,
  `until_at` DATETIME NULL,
  `occurrence_limit` INT UNSIGNED NULL,
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` TIMESTAMP NULL DEFAULT NULL,
  `updated_at` TIMESTAMP NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_tz_calendar_recurrence_event` (`calendar_event_id`),
  KEY `idx_tz_calendar_recurrence_team_active` (`team_id`,`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `tz_calendar_sync_accounts` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `team_id` BIGINT UNSIGNED NOT NULL,
  `company_id` BIGINT UNSIGNED DEFAULT NULL,
  `user_id` BIGINT UNSIGNED DEFAULT NULL,
  `created_by_team_id` BIGINT UNSIGNED DEFAULT NULL,
