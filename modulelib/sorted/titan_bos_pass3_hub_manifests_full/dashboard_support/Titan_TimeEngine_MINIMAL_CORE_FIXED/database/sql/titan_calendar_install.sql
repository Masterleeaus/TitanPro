CREATE TABLE IF NOT EXISTS `tz_scheduled_tasks` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `team_id` BIGINT UNSIGNED NOT NULL,
  `company_id` BIGINT UNSIGNED DEFAULT NULL,
  `user_id` BIGINT UNSIGNED DEFAULT NULL,
  `created_by_team_id` BIGINT UNSIGNED DEFAULT NULL,
  `task_type` VARCHAR(100) NOT NULL,
  `handler` VARCHAR(180) DEFAULT NULL,
  `status` VARCHAR(50) DEFAULT 'pending',
  `priority` INT DEFAULT 0,
  `scheduled_for` DATETIME NOT NULL,
  `next_run_at` DATETIME NULL,
  `last_run_at` DATETIME NULL,
  `executed_at` DATETIME NULL,
  `failed_at` DATETIME NULL,
  `retry_count` INT DEFAULT 0,
  `max_retries` INT DEFAULT 3,
  `related_type` VARCHAR(120) DEFAULT NULL,
  `related_id` BIGINT UNSIGNED DEFAULT NULL,
  `payload_json` JSON NULL,
  `result_json` JSON NULL,
  `created_at` TIMESTAMP NULL DEFAULT NULL,
  `updated_at` TIMESTAMP NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_tz_scheduled_tasks_team_status_run` (`team_id`,`status`,`scheduled_for`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
