    public function scan(?string $modulePath = null): array
    {
        $modulePath ??= function_exists('module_path') ? module_path('Security') : dirname(__DIR__, 2);
        $missing = [];
        $present = [];

        foreach ($this->expectedDirectories() as $directory) {
            $path = rtrim($modulePath, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $directory);
            if (is_dir($path)) {
                $present[] = $directory;
                continue;
            }
            $missing[] = $directory;
        }

        return [
            'module' => 'Security',
            'status' => $missing === [] ? 'ok' : 'incomplete',
            'expected_directories' => count($this->expectedDirectories()),
            'present_directories' => count($present),
            'missing_directories' => $missing,
            'coverage_percent' => count($this->expectedDirectories()) === 0
                ? 100
                : round((count($present) / count($this->expectedDirectories())) * 100, 2),
        ];
    }
